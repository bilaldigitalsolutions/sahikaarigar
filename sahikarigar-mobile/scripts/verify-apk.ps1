# =============================================================================
# verify-apk.ps1
# Proves whether a Sahi Kaarigar APK actually contains the static PNG tab-icon
# fix. Run this BEFORE installing an APK downloaded from GitHub Actions.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File scripts\verify-apk.ps1 <path-to-apk>
#
# Checks:
#   1. Embedded Expo config (versionName / versionCode).
#   2. The JS bundle contains the Metro asset path "assets/icons" - this string
#      exists only because _layout.tsx calls require('../../../assets/icons/*.png').
#   3. The APK carries the four generated PNG payloads (189/158/155/195 bytes,
#      resource names are obfuscated in release builds, so sizes are matched).
#
# Exit code: 0 = PASS, 1 = FAIL.
# =============================================================================
param(
    [Parameter(Mandatory = $true, Position = 0)]
    [string]$ApkPath
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression.FileSystem

if (-not (Test-Path $ApkPath)) {
    throw "APK not found: $ApkPath"
}

$apk = (Resolve-Path $ApkPath).Path
Write-Output "APK:  $apk"
Write-Output ("Size: {0:N1} MB" -f ((Get-Item $apk).Length / 1MB))
Write-Output ''

# Sizes of assets/icons/*.png generated by scripts/generate-tab-icons.ps1.
# Release builds have resource shrinking/obfuscation enabled (names change),
# but PNG crunching is disabled in app.json, so the bytes are preserved.
$expected = [ordered]@{
    'home.png'      = 189
    'briefcase.png' = 158
    'calendar.png'  = 155
    'person.png'    = 195
}

$zip = [System.IO.Compression.ZipFile]::OpenRead($apk)
try {
    # --- 1. Embedded Expo config -------------------------------------------
    $cfgEntry = $zip.GetEntry('assets/app.config')
    if ($cfgEntry) {
        $ms = New-Object System.IO.MemoryStream
        $s = $cfgEntry.Open()
        $s.CopyTo($ms)
        $s.Dispose()
        $cfg = ([Text.Encoding]::UTF8.GetString($ms.ToArray())) | ConvertFrom-Json
        Write-Output ("versionName: {0}" -f $cfg.version)
        Write-Output ("versionCode: {0}" -f $cfg.android.versionCode)
    }
    else {
        Write-Output 'versionName: <assets/app.config not found>'
    }

    # --- 2. JS bundle scan ---------------------------------------------------
    $bundleEntry = $zip.GetEntry('assets/index.android.bundle')
    if (-not $bundleEntry) {
        throw 'assets/index.android.bundle not found - is this a release APK?'
    }

    $ms = New-Object System.IO.MemoryStream
    $s = $bundleEntry.Open()
    $s.CopyTo($ms)
    $s.Dispose()
    $bytes = $ms.ToArray()
    $latin = [Text.Encoding]::GetEncoding(28591).GetString($bytes)
    Write-Output ("JS bundle: {0} bytes" -f $bytes.Length)

    $hasAssetPath = $latin.IndexOf('assets/icons', [StringComparison]::Ordinal) -ge 0
    Write-Output ("bundle contains 'assets/icons' (static PNG code): {0}" -f $hasAssetPath)
    Write-Output ''

    # --- 3. PNG payload check ------------------------------------------------
    $pngEntries = $zip.Entries | Where-Object {
        $_.FullName -like '*.png' -and $_.FullName -notlike '*.9.png'
    }
    $found = 0
    foreach ($name in $expected.Keys) {
        $size = $expected[$name]
        $hit = $pngEntries | Where-Object { $_.Length -eq $size } | Select-Object -First 1
        if ($hit) {
            $found++
            Write-Output ("icon payload {0,-14} ({1,3} bytes): FOUND as {2}" -f $name, $size, $hit.FullName)
        }
        else {
            Write-Output ("icon payload {0,-14} ({1,3} bytes): NOT FOUND" -f $name, $size)
        }
    }
    Write-Output ''

    # --- 4. Verdict ----------------------------------------------------------
    # The bundle path is authoritative: Metro emits it only for the require()
    # calls in (tabs)/_layout.tsx. Payload matches are confirmatory evidence.
    if ($hasAssetPath) {
        Write-Output 'VERDICT: PASS - this APK contains the static PNG tab-icon code.'
        if ($found -lt 4) {
            Write-Output ("         NOTE: only {0}/4 PNG payloads matched by exact size " -f $found)
            Write-Output '         (packaging may have re-encoded them; the bundle path still proves the code is present).'
        }
        exit 0
    }

    Write-Output 'VERDICT: FAIL - this APK does NOT contain the static PNG tab-icon code.'
    Write-Output '         Expected the Metro asset path "assets/icons" in the JS bundle.'
    exit 1
}
finally {
    $zip.Dispose()
}
